function normalizeClubName(name) {
    return name
        .toLowerCase()
        .replace(/&/g, "and")
        .replace(/\b(fc|afc|cf)\b/g, "")
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");
}

const team = Object.keys(clubs).find(key =>
    key === teamParam ||
    normalizeClubName(key) === normalizeClubName(teamParam || "") ||
    normalizeClubName(clubs[key].name) === normalizeClubName(teamParam || "")
);

