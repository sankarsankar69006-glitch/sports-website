const leagueGrid = document.getElementById("league-grid");
const teamsSection = document.getElementById("women-teams");
const teamGrid = document.getElementById("team-grid");

const leagueTitle = document.getElementById("selected-league-title");
const leagueDescription = document.getElementById("selected-league-description");
const teamCount = document.getElementById("team-count");

const modal = document.getElementById("team-modal");
const modalClose = document.getElementById("modal-close");


/* CREATE LEAGUE CARDS */

function displayLeagues() {

    leagueGrid.innerHTML = "";

    womensLeagues.forEach(league => {

        const card = document.createElement("article");

        card.className = "league-card";
        card.tabIndex = 0;
        card.setAttribute("role", "button");
        card.setAttribute("aria-label", `Explore ${league.name}`);

        card.style.setProperty(
            "--card-image",
            `url("${league.image}")`
        );

        card.innerHTML = `
            <div class="league-card-content">

                <span class="league-region">
                    ${league.region}
                </span>

                <h3>${league.name}</h3>

                <p>${league.description}</p>

                <div class="league-card-footer">
                    <span>Explore ${league.teams.length} sample clubs</span>
                    <i class="fa-solid fa-arrow-right"></i>
                </div>

            </div>
        `;

        card.addEventListener("click", () => {
            displayTeams(league.id);
        });

        card.addEventListener("keydown", event => {

            if (event.key === "Enter" || event.key === " ") {
                event.preventDefault();
                displayTeams(league.id);
            }

        });

        leagueGrid.appendChild(card);

    });

}


/* DISPLAY TEAMS FOR SELECTED LEAGUE */

function displayTeams(leagueId) {

    const league = womensLeagues.find(
        item => item.id === leagueId
    );

    if (!league) {
        return;
    }

    teamGrid.innerHTML = "";

    leagueTitle.textContent = league.name;
    leagueDescription.textContent = league.description;

    league.teams.forEach(team => {

        const card = document.createElement("article");

        card.className = "team-card";
        card.tabIndex = 0;
        card.setAttribute("role", "button");
        card.setAttribute("aria-label", `View ${team.name} details`);

        card.innerHTML = `
            <div class="team-image">
                <img
                    src="${team.image}"
                    alt="${team.name}"
                    loading="lazy"
                >
            </div>

            <div class="team-info">

                <span class="team-country">
                    ${team.country}
                </span>

                <h3>${team.name}</h3>

                <p class="team-founded">
                    Founded: ${team.founded}
                </p>

                <div class="team-view">
                    <span>View Details</span>
                    <i class="fa-solid fa-arrow-right"></i>
                </div>

            </div>
        `;

        const image = card.querySelector("img");

        image.addEventListener("error", () => {
            image.style.display = "none";
        });

        card.addEventListener("click", () => {
            showTeamDetails(team, league);
        });

        card.addEventListener("keydown", event => {

            if (event.key === "Enter" || event.key === " ") {
                event.preventDefault();
                showTeamDetails(team, league);
            }

        });

        teamGrid.appendChild(card);

    });

    teamCount.textContent =
        `${league.teams.length} sample clubs displayed`;

    teamsSection.hidden = false;

    teamsSection.scrollIntoView({
        behavior: "smooth",
        block: "start"
    });

}


/* TEAM DETAILS MODAL */

function showTeamDetails(team, league) {

    document.getElementById("modal-team-name").textContent =
        team.name;

    document.getElementById("modal-team-league").textContent =
        league.name;

    document.getElementById("modal-description").textContent =
        team.description;

    document.getElementById("modal-founded").textContent =
        team.founded;

    document.getElementById("modal-country").textContent =
        team.country;

    document.getElementById("modal-stadium").textContent =
        team.stadium;

    document.getElementById("modal-competition").textContent =
        league.name;

    document.getElementById("modal-cover").style.backgroundImage =
        `url("${team.image}")`;

    const achievementsList =
        document.getElementById("modal-achievements");

    achievementsList.innerHTML = "";

    team.achievements.forEach(achievement => {

        const item = document.createElement("li");

        const icon = document.createElement("i");
        icon.className = "fa-solid fa-check";

        const text = document.createElement("span");
        text.textContent = achievement;

        item.append(icon, text);
        achievementsList.appendChild(item);

    });

    modal.classList.add("active");
    modal.setAttribute("aria-hidden", "false");

    document.body.classList.add("modal-open");

    if (modalClose) {
        modalClose.focus();
    }

}


/* CLOSE MODAL */

function closeTeamModal() {

    if (modal) {
        modal.classList.remove("active");
        modal.setAttribute("aria-hidden", "true");
    }

    document.body.classList.remove("modal-open");

}

if (modalClose) {
    modalClose.addEventListener("click", closeTeamModal);
}

document.querySelectorAll("[data-close-modal]").forEach(element => {

    element.addEventListener("click", closeTeamModal);

});

document.addEventListener("keydown", event => {

    if (event.key === "Escape" && modal && modal.classList.contains("active")) {
        closeTeamModal();
    }

});


/* BACK TO ALL LEAGUES */

const backLeaguesBtn = document.getElementById("back-leagues");
if (backLeaguesBtn) {
    backLeaguesBtn.addEventListener("click", () => {
        if (teamsSection) {
            teamsSection.hidden = true;
        }

        const womenLeagues = document.getElementById("women-leagues");
        if (womenLeagues) {
            womenLeagues.scrollIntoView({
                behavior: "smooth",
                block: "start"
            });
        }
    });
}


